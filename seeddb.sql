-- ---------------------------------------------------------------------
-- 1. HÀM DÙNG CHUNG (MÚI GIỜ VIỆT NAM & AUTO UPDATED_AT)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION vn_now() RETURNS timestamp
LANGUAGE sql STABLE AS 'SELECT (now() AT TIME ZONE ''Asia/Ho_Chi_Minh'')';

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS 'BEGIN NEW.updated_at := (now() AT TIME ZONE ''Asia/Ho_Chi_Minh''); RETURN NEW; END';

-- ---------------------------------------------------------------------
-- 2. TÀI KHOẢN NGƯỜI DÙNG (CUSTOMERS - F1)
-- ---------------------------------------------------------------------
CREATE TABLE customers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(150) NOT NULL,
    email           VARCHAR(150) NOT NULL,
    phone           VARCHAR(20)  NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    password_changed_at TIMESTAMP,
    date_of_birth   DATE,
    address         VARCHAR(300),
    avatar_url      VARCHAR(500),
    zalo_phone      VARCHAR(20),
    contact_note    VARCHAR(255),
    email_verified  BOOLEAN      NOT NULL DEFAULT FALSE,
    kyc_status      VARCHAR(20)  NOT NULL DEFAULT 'NONE'
                    CHECK (kyc_status IN ('NONE', 'PENDING', 'VERIFIED', 'REJECTED')),
    role            VARCHAR(20)  NOT NULL DEFAULT 'CUSTOMER'
                    CHECK (role IN ('CUSTOMER', 'OWNER', 'ADMIN')),
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
                    CHECK (status IN ('ACTIVE', 'LOCKED')),
    created_at      TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT vn_now()
);
CREATE UNIQUE INDEX uq_customers_email_lower ON customers (lower(email));

-- ---------------------------------------------------------------------
-- 3. GIẤY TỜ XÁC MINH DANH TÍNH (USER_DOCUMENTS - KYC F1)
-- ---------------------------------------------------------------------
CREATE TABLE user_documents (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id          BIGINT       NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    doc_type             VARCHAR(30)  NOT NULL
                         CHECK (doc_type IN ('CITIZEN_ID', 'DRIVER_LICENSE', 'PASSPORT')),
    doc_number           VARCHAR(50)  NOT NULL,
    full_name_on_doc     VARCHAR(150),
    date_of_birth_on_doc DATE,
    issue_place          VARCHAR(200),
    issue_date           DATE,
    expires_at           DATE,
    license_class        VARCHAR(10),
    front_image_url      VARCHAR(500) NOT NULL,
    back_image_url       VARCHAR(500),
    verify_status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                         CHECK (verify_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reject_reason        VARCHAR(500),
    verified_by          BIGINT       REFERENCES customers(id),
    verified_at          TIMESTAMP,
    created_at           TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at           TIMESTAMP    NOT NULL DEFAULT vn_now(),
    CHECK (issue_date IS NULL OR expires_at IS NULL OR issue_date <= expires_at),
    CHECK (doc_type <> 'DRIVER_LICENSE' OR license_class IS NOT NULL)
);
CREATE UNIQUE INDEX uq_user_doc_approved
    ON user_documents (doc_type, doc_number) WHERE verify_status = 'APPROVED';

-- ---------------------------------------------------------------------
-- 4. GÓI ĐĂNG TIN THEO QUOTA SLOTS (LISTING_PACKAGES - F1 & F3)
-- ---------------------------------------------------------------------
CREATE TABLE listing_packages (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(100) NOT NULL,
    code                   VARCHAR(50)  NOT NULL UNIQUE,
    price                  NUMERIC(14,0) NOT NULL CHECK (price >= 0),
    duration_days          INT          NOT NULL CHECK (duration_days > 0),
    slot_count             INT          NOT NULL DEFAULT 1 CHECK (slot_count > 0),
    duration_days_per_slot INT          NOT NULL DEFAULT 7 CHECK (duration_days_per_slot > 0),
    priority_level         INT          NOT NULL DEFAULT 1 CHECK (priority_level IN (1, 2, 3)),
    badge_label            VARCHAR(50)  NOT NULL DEFAULT 'THƯỜNG',
    description            TEXT,
    is_active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at             TIMESTAMP    NOT NULL DEFAULT vn_now()
);

-- ---------------------------------------------------------------------
-- 5. MÃ GIẢM GIÁ (VOUCHERS - F1)
-- ---------------------------------------------------------------------
CREATE TABLE vouchers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(50)  NOT NULL UNIQUE,
    description      VARCHAR(300),
    discount_type    VARCHAR(10)  NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    discount_value   NUMERIC(14,0) NOT NULL CHECK (discount_value > 0),
    max_discount     NUMERIC(14,0) CHECK (max_discount >= 0),
    min_order_amount NUMERIC(14,0) NOT NULL DEFAULT 0 CHECK (min_order_amount >= 0),
    start_at         TIMESTAMP    NOT NULL,
    end_at           TIMESTAMP    NOT NULL,
    usage_limit      INT          CHECK (usage_limit > 0),
    per_user_limit   INT          NOT NULL DEFAULT 1 CHECK (per_user_limit > 0),
    used_count       INT          NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    status           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at       TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at       TIMESTAMP    NOT NULL DEFAULT vn_now(),
    CHECK (end_at > start_at),
    CHECK (discount_type <> 'PERCENT' OR discount_value <= 100),
    CHECK (usage_limit IS NULL OR used_count <= usage_limit)
);

-- ---------------------------------------------------------------------
-- 6. QUẢN LÝ XE & HỒ SƠ TIN ĐĂNG (CARS - F2)
-- ---------------------------------------------------------------------
CREATE TABLE cars (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             BIGINT       NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    license_plate        VARCHAR(20)  NOT NULL UNIQUE,
    brand                VARCHAR(50)  NOT NULL,
    model                VARCHAR(50)  NOT NULL,
    manufacture_year     INT          NOT NULL CHECK (manufacture_year BETWEEN 1990 AND 2100),
    car_type             VARCHAR(20)  NOT NULL
                         CHECK (car_type IN ('SEDAN', 'HATCHBACK', 'SUV', 'MPV', 'PICKUP', 'LUXURY', 'OTHER')),
    seats                INT          NOT NULL CHECK (seats > 0),
    transmission         VARCHAR(20)  NOT NULL CHECK (transmission IN ('MANUAL', 'AUTOMATIC')),
    fuel_type            VARCHAR(20)  NOT NULL CHECK (fuel_type IN ('GASOLINE', 'DIESEL', 'ELECTRIC', 'HYBRID')),
    color                VARCHAR(30),
    description          TEXT,
    features             JSONB        NOT NULL DEFAULT '[]'::jsonb,
    city                 VARCHAR(100) NOT NULL,
    district             VARCHAR(100),
    pickup_address       VARCHAR(300) NOT NULL,
    latitude             NUMERIC(9,6),
    longitude            NUMERIC(9,6),
    
    rental_price_per_day   NUMERIC(14,0) CHECK (rental_price_per_day >= 0),
    rental_price_per_month NUMERIC(14,0) CHECK (rental_price_per_month >= 0),
    weekend_price_per_day  NUMERIC(14,0) CHECK (weekend_price_per_day >= 0),
    deposit_amount         NUMERIC(14,0) CHECK (deposit_amount >= 0),
    km_limit_per_day       INT CHECK (km_limit_per_day > 0),
    extra_km_fee           NUMERIC(14,0) CHECK (extra_km_fee >= 0),
    late_fee_per_hour      NUMERIC(14,0) CHECK (late_fee_per_hour >= 0),
    
    contact_name         VARCHAR(150),
    contact_phone        VARCHAR(20),
    contact_zalo         VARCHAR(20),
    
    status               VARCHAR(20)  NOT NULL DEFAULT 'PENDING_APPROVAL'
                         CHECK (status IN ('PENDING_APPROVAL', 'ACTIVE', 'INACTIVE', 'REJECTED')),
    listing_status       VARCHAR(20)  NOT NULL DEFAULT 'UNLISTED'
                         CHECK (listing_status IN ('UNLISTED', 'LISTED', 'EXPIRED')),
                         
    reject_reason        VARCHAR(500),
    current_subscription_id BIGINT,
    created_at           TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at           TIMESTAMP    NOT NULL DEFAULT vn_now()
);

-- ---------------------------------------------------------------------
-- 7. HÌNH ẢNH XE (CAR_IMAGES - F2)
-- ---------------------------------------------------------------------
CREATE TABLE car_images (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id          BIGINT       NOT NULL REFERENCES cars(id) ON DELETE CASCADE,
    image_url       VARCHAR(500) NOT NULL,
    is_primary      BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order      INT          NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_car_primary_image ON car_images (car_id) WHERE is_primary;

-- ---------------------------------------------------------------------
-- 8. GIẤY TỜ XE (CAR_DOCUMENTS - F2)
-- ---------------------------------------------------------------------
CREATE TABLE car_documents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id          BIGINT       NOT NULL REFERENCES cars(id) ON DELETE CASCADE,
    doc_type        VARCHAR(30)  NOT NULL
                    CHECK (doc_type IN ('REGISTRATION', 'INSPECTION', 'INSURANCE')),
    file_url        VARCHAR(500) NOT NULL,
    expires_at      DATE,
    verify_status   VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                    CHECK (verify_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reject_reason   VARCHAR(500),
    verified_by     BIGINT       REFERENCES customers(id),
    verified_at     TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT vn_now()
);

-- ---------------------------------------------------------------------
-- 9. ĐĂNG KÝ GÓI ĐĂNG TIN (CAR_SUBSCRIPTIONS - F3)
-- ---------------------------------------------------------------------
CREATE TABLE car_subscriptions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_code       VARCHAR(50)  NOT NULL UNIQUE,
    customer_id             BIGINT       NOT NULL REFERENCES customers(id),
    car_id                  BIGINT       NOT NULL REFERENCES cars(id) ON DELETE CASCADE,
    package_id              BIGINT       NOT NULL REFERENCES listing_packages(id),
    voucher_id              BIGINT       REFERENCES vouchers(id),
    
    package_price           NUMERIC(14,0) NOT NULL CHECK (package_price >= 0),
    discount_amount         NUMERIC(14,0) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total_amount            NUMERIC(14,0) NOT NULL CHECK (total_amount >= 0),
    
    status                  VARCHAR(20)  NOT NULL DEFAULT 'PENDING_PAYMENT'
                            CHECK (status IN ('PENDING_PAYMENT', 'ACTIVE', 'EXPIRED', 'CANCELLED')),
    payment_status          VARCHAR(20)  NOT NULL DEFAULT 'UNPAID'
                            CHECK (payment_status IN ('UNPAID', 'PAID', 'REFUNDED')),
                            
    total_slots             INT          NOT NULL DEFAULT 1 CHECK (total_slots > 0),
    remaining_slots         INT          NOT NULL DEFAULT 0 CHECK (remaining_slots >= 0),
    duration_days_per_slot  INT          NOT NULL DEFAULT 7 CHECK (duration_days_per_slot > 0),
    current_slot_start_date TIMESTAMP,
    current_slot_end_date   TIMESTAMP,
    start_date              TIMESTAMP,
    end_date                TIMESTAMP,
    activated_at            TIMESTAMP,
    created_at              TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at              TIMESTAMP    NOT NULL DEFAULT vn_now(),
    CHECK (discount_amount <= package_price),
    CHECK (total_amount = package_price - discount_amount),
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date > start_date)
);

-- Ràng buộc liên kết cars -> car_subscriptions
ALTER TABLE cars 
    ADD CONSTRAINT fk_cars_subscription 
    FOREIGN KEY (current_subscription_id) REFERENCES car_subscriptions(id) ON DELETE SET NULL;

-- ---------------------------------------------------------------------
-- 10. GIAO DỊCH THANH TOÁN (TRANSACTIONS - F4)
-- ---------------------------------------------------------------------
CREATE TABLE transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id  BIGINT       REFERENCES car_subscriptions(id) ON DELETE CASCADE,
    booking_id       BIGINT       , -- FK được thêm trong schema_updates.sql sau khi bảng bookings được tạo
    transaction_type VARCHAR(20)  NOT NULL DEFAULT 'PACKAGE_PAYMENT'
                     CHECK (transaction_type IN ('PACKAGE_PAYMENT', 'BOOKING_DEPOSIT', 'BOOKING_REFUND', 'REFUND')),
    amount           NUMERIC(14,0) NOT NULL CHECK (amount > 0),
    method           VARCHAR(20)  NOT NULL CHECK (method IN ('BANK_TRANSFER', 'MOMO', 'VNPAY', 'CASH')),
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    provider_ref     VARCHAR(100),
    paid_at          TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT vn_now(),
    updated_at       TIMESTAMP    NOT NULL DEFAULT vn_now()
);

-- ---------------------------------------------------------------------
-- 11. ĐÁNH GIÁ XE & CHỦ XE (REVIEWS - F4)
-- ---------------------------------------------------------------------
CREATE TABLE reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id          BIGINT       NOT NULL REFERENCES cars(id) ON DELETE CASCADE,
    customer_id     BIGINT       NOT NULL REFERENCES customers(id),
    rating          INT          NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT,
    approved        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL DEFAULT vn_now()
);

