-- ---------------------------------------------------------------------
-- HỒ SƠ AN TOÀN XE (CAR_SAFETY_RECORDS): đăng kiểm, bảo hiểm, bảo dưỡng, sửa chữa
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS car_safety_records (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id           BIGINT       NOT NULL REFERENCES cars(id) ON DELETE CASCADE,
    record_type      VARCHAR(20)  NOT NULL CHECK (record_type IN ('INSPECTION', 'INSURANCE', 'MAINTENANCE', 'REPAIR')),
    performed_at     DATE         NOT NULL,
    expires_at       DATE,
    provider         VARCHAR(200),
    reference_number VARCHAR(60),
    odometer_km      INT CHECK (odometer_km >= 0),
    result           VARCHAR(20)  NOT NULL DEFAULT 'NOT_APPLICABLE' CHECK (result IN ('PASSED', 'FAILED', 'NOT_APPLICABLE')),
    note             VARCHAR(1000),
    file_url         VARCHAR(500),
    verify_status    VARCHAR(20)  NOT NULL DEFAULT 'PENDING' CHECK (verify_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reject_reason    VARCHAR(500),
    verified_by      BIGINT REFERENCES customers(id) ON DELETE SET NULL,
    verified_at      TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    updated_at       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    CHECK (expires_at IS NULL OR expires_at >= performed_at)
);
CREATE INDEX IF NOT EXISTS idx_car_safety_records_car ON car_safety_records (car_id, performed_at DESC);

-- ---------------------------------------------------------------------
-- ĐƠN THUÊ XE + BIÊN BẢN BÀN GIAO
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bookings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code       VARCHAR(30)  NOT NULL UNIQUE,
    car_id             BIGINT       NOT NULL REFERENCES cars(id) ON DELETE RESTRICT,
    customer_id        BIGINT       NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    owner_id           BIGINT       NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    pickup_at          TIMESTAMP    NOT NULL,
    return_at          TIMESTAMP    NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED','CONFIRMED','REJECTED',
                       'CANCELLED','EXPIRED','PICKUP_PENDING','IN_PROGRESS','RETURN_PENDING','COMPLETED')),
    rental_days        INT          NOT NULL CHECK (rental_days >= 0),
    rental_hours       INT          NOT NULL CHECK (rental_hours BETWEEN 0 AND 23),
    price_per_day      NUMERIC(14,0) NOT NULL,
    price_per_hour     NUMERIC(14,0) NOT NULL,
    day_amount         NUMERIC(14,0) NOT NULL,
    hour_amount        NUMERIC(14,0) NOT NULL,
    rental_amount      NUMERIC(14,0) NOT NULL CHECK (rental_amount >= 0),
    deposit_amount     NUMERIC(14,0) NOT NULL DEFAULT 0,
    km_limit_per_day   INT,
    extra_km_fee       NUMERIC(14,0),
    late_fee_per_hour  NUMERIC(14,0),
    customer_note      VARCHAR(1000),
    contact_phone      VARCHAR(20),
    owner_contacted_at TIMESTAMP,
    contact_note       VARCHAR(1000),
    confirmed_at       TIMESTAMP,
    reject_reason      VARCHAR(500),
    cancel_reason      VARCHAR(500),
    cancelled_by       VARCHAR(20),
    picked_up_at       TIMESTAMP,
    returned_at        TIMESTAMP,
    pickup_odometer_km INT,
    return_odometer_km INT,
    extra_km_amount    NUMERIC(14,0) DEFAULT 0,
    late_amount        NUMERIC(14,0) DEFAULT 0,
    other_fee_amount   NUMERIC(14,0) DEFAULT 0,
    other_fee_note     VARCHAR(500),
    final_amount       NUMERIC(14,0),
    completed_at       TIMESTAMP,
    created_at         TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    updated_at         TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    CHECK (return_at > pickup_at),
    CHECK (customer_id <> owner_id)
);
CREATE INDEX IF NOT EXISTS idx_bookings_car_time ON bookings (car_id, pickup_at, return_at);
CREATE INDEX IF NOT EXISTS idx_bookings_customer ON bookings (customer_id);
CREATE INDEX IF NOT EXISTS idx_bookings_owner ON bookings (owner_id);

CREATE TABLE IF NOT EXISTS handovers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     BIGINT      NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    handover_type  VARCHAR(10) NOT NULL CHECK (handover_type IN ('PICKUP','RETURN')),
    status         VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED' CHECK (status IN ('SUBMITTED','DISPUTED','CONFIRMED')),
    odometer_km    INT         NOT NULL CHECK (odometer_km >= 0),
    fuel_percent   INT         NOT NULL CHECK (fuel_percent BETWEEN 0 AND 100),
    owner_note     VARCHAR(1000),
    customer_note  VARCHAR(1000),
    revision       INT         NOT NULL DEFAULT 1,
    submitted_at   TIMESTAMP   NOT NULL,
    confirmed_at   TIMESTAMP,
    created_at     TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    updated_at     TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh'),
    UNIQUE (booking_id, handover_type)
);

CREATE TABLE IF NOT EXISTS handover_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id    BIGINT       NOT NULL REFERENCES handovers(id) ON DELETE CASCADE,
    category       VARCHAR(30)  NOT NULL,
    photo_url      VARCHAR(500) NOT NULL,
    condition_note VARCHAR(1000),
    status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACCEPTED','DISPUTED','REVISED')),
    dispute_note   VARCHAR(1000),
    sort_order     INT          NOT NULL DEFAULT 0
);

